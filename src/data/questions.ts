export function getStateFromCPF(cpf: string): string {
  const digits = cpf.replace(/\D/g, '');
  if (digits.length < 3) return 'SP';
  const digit = digits[digits.length - 3];
  return CPF_STATE_MAP[digit] || 'SP';
}

function seededShuffle<T>(arr: T[], seed: number): T[] {
  const a = [...arr];
  let x = seed;
  for (let i = a.length - 1; i > 0; i--) {
    x = (Math.imul(x, 1664525) + 1013904223) | 0;
    const j = Math.abs(x) % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

