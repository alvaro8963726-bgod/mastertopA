export function getQuestionsBySubject(subject: string, count = 30, seed?: number): Question[] {
  const bySubject = ALL_QUESTIONS.filter((q) => q.subject === subject);
  const others    = ALL_QUESTIONS.filter((q) => q.subject !== subject);
  const s = seed ?? Date.now();
  const shuffledSub   = seededShuffle(bySubject, s);
  const shuffledOther = seededShuffle(others, s + 1);
  return [...shuffledSub, ...shuffledOther].slice(0, count);
}
